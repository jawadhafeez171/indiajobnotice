/**
 * Helper: Retrieve all districts registered for a specific state
 */
export function getDistrictsByState(stateSlug: string): DistrictInfo[] {
  return DISTRICTS_REGISTRY.filter(
    (d) => d.stateSlug.toLowerCase() === stateSlug.toLowerCase()
  );
}

/**
 * Helper: Retrieve a specific district by stateSlug and districtSlug
 */
export function getDistrictBySlug(stateSlug: string, districtSlug: string): DistrictInfo | undefined {
  return DISTRICTS_REGISTRY.find(
    (d) =>
      d.stateSlug.toLowerCase() === stateSlug.toLowerCase() &&
      d.slug.toLowerCase() === districtSlug.toLowerCase()
  );
}

/**
 * Helper: Retrieve top major recruitment hub districts for quick filter chips
 */
export function getMajorDistricts(stateSlug: string, limit: number = 8): DistrictInfo[] {
  const districts = getDistrictsByState(stateSlug);
  const major = districts.filter((d) => d.isMajorHub);
  if (major.length >= limit) return major.slice(0, limit);
  // Pad with additional districts if major list is short
  return [...major, ...districts.filter((d) => !d.isMajorHub)].slice(0, limit);
}

/**
 * Helper: Retrieve all districts
 */
export function getAllDistricts(): DistrictInfo[] {
  return DISTRICTS_REGISTRY;
}
